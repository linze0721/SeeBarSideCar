var (
	hidToWin = map[uint16]WinScan{}
	winToHID = map[WinScan]uint16{}
	hidToMac = map[uint16]uint16{}
	macToHID = map[uint16]uint16{}
)

func init() {
	if err := build(rows); err != nil {
		panic(err)
	}
}

// build fills the maps from rs, rejecting any duplicate key in any direction
// so an inverse lookup can never silently pick the wrong row.
func build(rs []row) error {
	seen := map[uint16]bool{}
	for _, r := range rs {
		if seen[r.hid] {
			return fmt.Errorf("keymap: duplicate HID usage %#x", r.hid)
		}
		seen[r.hid] = true
		if r.win != 0 {
			s := WinScan{r.win, r.ext}
			if h, dup := winToHID[s]; dup {
				return fmt.Errorf("keymap: win scan %+v used by HID %#x and %#x", s, h, r.hid)
			}
			hidToWin[r.hid] = s
			winToHID[s] = r.hid
		}
		if r.mac != noMac {
			if h, dup := macToHID[r.mac]; dup {
				return fmt.Errorf("keymap: mac code %#x used by HID %#x and %#x", r.mac, h, r.hid)
			}
			hidToMac[r.hid] = r.mac
			macToHID[r.mac] = r.hid
		}
	}
	return nil
}
